def get_key_metrics(ticker):
    company = _get_company(ticker)
    financials = company.get_financials()
    if financials is None:
        return {}

    metrics = {}
    try:
        metrics["revenue"] = financials.get_revenue()
    except Exception:
        pass
    try:
        metrics["net_income"] = financials.get_net_income()
    except Exception:
        pass
    try:
        metrics["operating_income"] = financials.get_operating_income()
    except Exception:
        pass
    try:
        metrics["total_assets"] = financials.get_total_assets()
    except Exception:
        pass
    try:
        metrics["total_liabilities"] = financials.get_total_liabilities()
    except Exception:
        pass
    try:
        metrics["stockholders_equity"] = financials.get_stockholders_equity()
    except Exception:
        pass
    try:
        ocf = financials.get_operating_cash_flow()
        if ocf is None:
            # Fallback: extract from cash flow statement DataFrame
            cf_df = financials.cashflow_statement().to_dataframe()
            cf_indexed = cf_df.set_index("label") if "label" in cf_df.columns else cf_df
            for label in ["Cash generated by operating activities", "Net cash from operating activities"]:
                if label in cf_indexed.index:
                    row = cf_indexed.loc[label]
                    period_col = [c for c in row.index if c.startswith("FY") or c.startswith("20")]
                    if period_col:
                        val = row[period_col[0]]
                        if pd.notna(val):
                            ocf = float(val)
                            break
        metrics["operating_cash_flow"] = ocf
    except Exception:
        pass
    try:
        fcf = financials.get_free_cash_flow()
        if fcf is None:
            # Fallback: compute OCF - CapEx
            ocf_val = metrics.get("operating_cash_flow")
            capex = financials.get_capital_expenditures()
            if ocf_val and capex:
                fcf = ocf_val - abs(capex)
        metrics["free_cash_flow"] = fcf
    except Exception:
        pass
    try:
        metrics["current_assets"] = financials.get_current_assets()
    except Exception:
        pass
    try:
        metrics["current_liabilities"] = financials.get_current_liabilities()
    except Exception:
        pass

    if metrics.get("revenue") and metrics.get("net_income"):
        metrics["net_margin"] = metrics["net_income"] / metrics["revenue"]
    if metrics.get("revenue") and metrics.get("operating_income"):
        metrics["operating_margin"] = metrics["operating_income"] / metrics["revenue"]
    if metrics.get("current_assets") and metrics.get("current_liabilities") and metrics["current_liabilities"] > 0:
        metrics["current_ratio"] = metrics["current_assets"] / metrics["current_liabilities"]
    if metrics.get("total_liabilities") and metrics.get("stockholders_equity") and metrics["stockholders_equity"] > 0:
        metrics["debt_to_equity"] = metrics["total_liabilities"] / metrics["stockholders_equity"]
    if metrics.get("net_income") and metrics.get("stockholders_equity") and metrics["stockholders_equity"] > 0:
        metrics["roe"] = metrics["net_income"] / metrics["stockholders_equity"]

    return metrics


def compute_yoy_changes(ticker):
    company = _get_company(ticker)
    stmt = company.income_statement(periods=4)
    if stmt is None:
        return None

    df = stmt.to_dataframe()
    period_cols = [c for c in df.columns if c.startswith("FY") or c.startswith("20")]
    if len(period_cols) < 2:
        return None

    # The DataFrame is already indexed by concept from the statement
    changes = {}

    key_concepts = [
        "RevenueFromContractWithCustomerExcludingAssessedTax",
        "Revenue",
        "GrossProfit",
        "OperatingIncomeLoss",
        "NetIncomeLoss",
        "NetIncome",
        "CostOfGoodsAndServicesSold",
        "OperatingExpenses",
    ]

    # Build a mapping from concept to label for display names
    label_map = {}
    if "label" in df.columns:
        for concept_name in df.index:
            label_map[concept_name] = df.loc[concept_name, "label"] if concept_name in df.index else concept_name

    for concept in key_concepts:
        if concept in df.index:
            row = df.loc[concept]
            values = [(c, row[c]) for c in period_cols if pd.notna(row.get(c))]
            if len(values) >= 2:
                latest = values[0][1]
                prior = values[1][1]
                if prior and prior != 0:
                    pct = ((latest - prior) / abs(prior)) * 100
                    display_name = label_map.get(concept, concept)
                    changes[display_name] = {
                        "latest_period": values[0][0],
                        "latest_value": float(latest),
                        "prior_period": values[1][0],
                        "prior_value": float(prior),
                        "yoy_change_pct": round(pct, 2),
                    }
    return changes


def get_financial_summary_as_markdown(ticker):
    company = _get_company(ticker)
    financials = company.get_financials()
    if financials is None:
        return None

    parts = []
    parts.append(f"# {ticker} Financial Summary\n")

    try:
        income = financials.income_statement()
        parts.append("## Income Statement")
        parts.append(income.to_markdown())
    except Exception:
        pass

    try:
        balance = financials.balance_sheet()
        parts.append("\n## Balance Sheet")
        parts.append(balance.to_markdown())
    except Exception:
        pass

    try:
        cashflow = financials.cashflow_statement()
        parts.append("\n## Cash Flow Statement")
        parts.append(cashflow.to_markdown())
    except Exception:
        pass

    return "\n".join(parts)


def get_notes_as_markdown(ticker, focus=None):
    company = _get_company(ticker)
    tenk = company.get_filings(form="10-K").latest().obj()
    if tenk is None:
        return None

    parts = []
    try:
        notes = tenk.notes
        if notes:
            if focus:
                md = notes.to_markdown(focus=focus)
            else:
                md = notes.to_markdown()
            parts.append(md)
    except Exception:
        pass

    return "\n".join(parts) if parts else None


def get_filing_sections(ticker, sections=None):
    company = _get_company(ticker)
    tenk = company.get_filings(form="10-K").latest().obj()
    if tenk is None:
        return {}

    results = {}
    if sections is None:
        sections = ["Item 1", "Item 1A", "Item 7"]

    for section_name in sections:
        try:
            report = tenk.get_report(section_name)
            if report:
                results[section_name] = report.text[:3000] if hasattr(report, "text") else str(report)[:3000]
        except Exception:
            try:
                item = tenk[section_name]
                if item:
                    results[section_name] = str(item)[:3000]
            except Exception:
                pass

    return results


