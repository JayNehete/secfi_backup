def _init_identity():
    set_identity(config.EDGAR_IDENTITY)


def _get_company(ticker):
    _init_identity()
    return Company(ticker)


def get_financials(ticker):
    company = _get_company(ticker)
    return company.get_financials()


def get_multi_period_statements(ticker, form="10-K", periods=4):
    company = _get_company(ticker)
    filings = company.get_filings(form=form).filter(amendments=False).head(periods)
    if len(filings) == 0:
        return None
    xbrls = XBRLS.from_filings(filings)
    return xbrls


