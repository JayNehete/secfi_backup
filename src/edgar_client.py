def _extract_facts_from_filing(filing, query_text, form_type):
    """Extract matching facts from a single filing using DataFrame."""
    results = []
    try:
        xbrl = filing.xbrl()
        if xbrl is None:
            return results
        df = xbrl.facts.to_dataframe()
        filing_date = str(filing.filing_date)
        period = str(filing.period_of_report) if hasattr(filing, "period_of_report") else filing_date

        query_lower = query_text.lower()

        # Get concept substrings to search for
        search_terms = CONCEPT_ALIASES.get(query_lower, [query_lower.replace(" ", "")])

        for term in search_terms:
            matches = df[df["concept"].str.lower().str.contains(term, na=False)]
            # Filter to non-dimensioned rows (consolidated figures)
            if "is_dimensioned" in matches.columns:
                consolidated = matches[matches["is_dimensioned"] == False]
                if len(consolidated) > 0:
                    matches = consolidated

            # Keep only the most recent quarterly view (duration periods, not YTD)
            if "period_key" in matches.columns and len(matches) > 0:
                duration_rows = matches[matches["period_key"].str.startswith("duration", na=False)]
                if len(duration_rows) > 0:
                    matches = duration_rows

            # Deduplicate by concept, keeping the first (most recent) occurrence
            seen_concepts = set()
            for _, row in matches.iterrows():
                concept = str(row.get("concept", ""))
                if concept in seen_concepts:
                    continue
                seen_concepts.add(concept)
                value = row.get("numeric_value", row.get("value"))
                unit = str(row.get("unit_ref", row.get("currency", "")))
                label = str(row.get("label", row.get("original_label", concept)))

                # Convert to float if possible
                try:
                    value = float(value) if value is not None else None
                except (ValueError, TypeError):
                    value = row.get("value")

                dedup_key = f"{concept}_{value}_{period}"
                results.append({
                    "concept": concept,
                    "label": label,
                    "value": value,
                    "unit": unit,
                    "period": period,
                    "filing_date": filing_date,
                    "form_type": form_type,
                })
    except Exception as e:
        console.print(f"[dim]Error extracting XBRL facts: {e}[/dim]")

    # For "effective tax rate", compute it from tax expense / pre-tax income
    if query_lower in ("effective tax rate", "tax rate"):
        results = _compute_effective_tax_rate(df, filing_date, period, form_type, results)

    return results


def _compute_effective_tax_rate(df, filing_date, period, form_type, existing_results):
    """Compute effective tax rate from XBRL facts if raw concepts found."""
    try:
        tax_expense_rows = df[df["concept"].str.lower().str.contains("incometaxexpensebenefit", na=False)]
        pretax_income_rows = df[df["concept"].str.lower().str.contains("incomelossfromcontinuingoperationsbeforeincometaxes", na=False)]

        if "is_dimensioned" in tax_expense_rows.columns:
            tax_expense_rows = tax_expense_rows[tax_expense_rows["is_dimensioned"] == False]
            pretax_income_rows = pretax_income_rows[pretax_income_rows["is_dimensioned"] == False]

        if len(tax_expense_rows) == 0 or len(pretax_income_rows) == 0:
            return existing_results

        # Use the first (most recent) non-dimensioned values with valid numbers
        for _, trow in tax_expense_rows.iterrows():
            try:
                tax_val = float(trow.get("numeric_value", 0))
                if tax_val == 0 or tax_val != tax_val:  # skip zero or NaN
                    continue
                # Find matching pretax row
                for _, prow in pretax_income_rows.iterrows():
                    try:
                        pretax_val = float(prow.get("numeric_value", 0))
                        if pretax_val == 0 or pretax_val != pretax_val:  # skip zero or NaN
                            continue
                        effective_rate = tax_val / pretax_val
                        return [{
                            "concept": "us-gaap:EffectiveIncomeTaxRate (computed)",
                            "label": "Effective Income Tax Rate",
                            "value": effective_rate,
                            "unit": "percent",
                            "period": period,
                            "filing_date": filing_date,
                            "form_type": form_type,
                        }]
                    except (ValueError, TypeError):
                        continue
            except (ValueError, TypeError):
                continue
    except Exception:
        pass

    return existing_results


def get_company_facts_list(ticker, form_type="10-Q"):
    """Get the full list of available XBRL concepts for a company's latest filing."""
    company = _get_company(ticker)
    filings_obj = company.get_filings(form=form_type)
    filing = filings_obj.filter(amendments=False).latest()
    if filing is None:
        return []
    xbrl = filing.xbrl()
    if xbrl is None:
        return []
    df = xbrl.facts.to_dataframe()
    return df["concept"].unique().tolist()
