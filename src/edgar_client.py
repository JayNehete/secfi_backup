def get_filing_metadata(ticker, form_type="10-Q", count=5):
    """Get filing metadata: dates, accession numbers, periods."""
    company = _get_company(ticker)
    filings = company.get_filings(form=form_type).filter(amendments=False).head(count)
    if len(filings) == 0:
        return []

    results = []
    for f in filings:
        meta = {
            "form": f.form,
            "filing_date": str(f.filing_date),
            "period_of_report": str(f.period_of_report) if hasattr(f, "period_of_report") else None,
            "accession_no": f.accession_no,
            "company": f.company,
        }
        results.append(meta)
    return results


def get_latest_filing_date(ticker, form_type="10-Q"):
    """Get just the most recent filing date for a form type."""
    meta = get_filing_metadata(ticker, form_type, count=1)
    if meta:
        return meta[0]
    return None


def search_xbrl_facts(ticker, query_text, form_type=None, periods_back=3):
    """Search for XBRL facts by concept query. Returns matching facts from DataFrame."""
    company = _get_company(ticker)

    if form_type:
        filings_obj = company.get_filings(form=form_type)
        filing = filings_obj.filter(amendments=False).latest()
        if filing is None:
            return []
        return _extract_facts_from_filing(filing, query_text, form_type)

    results = []
    forms_to_try = ["10-K", "10-Q"]
    for form in forms_to_try:
        try:
            filings_obj = company.get_filings(form=form)
            recent = filings_obj.filter(amendments=False).head(periods_back)
            for f in recent:
                found = _extract_facts_from_filing(f, query_text, form)
                results.extend(found)
        except Exception:
            continue

    return results


